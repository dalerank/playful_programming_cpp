long long resolve_targets(vector<Enemy*>& v) {
    sort(v.begin(), v.end(), [](const Enemy* a, const Enemy* b) {
        if (a->dmg != b->dmg) return a->dmg > b->dmg;
        return a < b;                    // <- ? ??? ??? ???????????? ??????
    });
    long long acc = 0;
    for (const Enemy* e : v) acc = acc * 31 + e->id;   // ??????? ?????
    return acc;
}

